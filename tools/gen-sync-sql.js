/* Generate a FULL-OVERWRITE resync of people content from assets/data.js.
 *
 * This is deliberately different from gen-seed-sql.js. `seed.sql` fills only
 * blank fields so it can never undo a family correction. This one replaces
 * the text outright, so it is the right tool in exactly one situation: the
 * canonical text in data.js has been revised and no one has yet edited the
 * live database. Check that `suggestions` is empty before running it.
 *
 *   node tools/gen-sync-sql.js
 */

const path = require('path');
const fs = require('fs');
const { SEED_PEOPLE } = require(path.join(__dirname, '..', 'assets', 'data.js'));

const TEXT = ['name', 'name_ur', 'birth', 'birth_ur', 'death', 'death_ur',
  'birthplace', 'birthplace_ur', 'residence', 'residence_ur',
  'spouse', 'spouse_ur', 'notes', 'notes_ur', 'tag'];

const q = s => "'" + String(s == null ? '' : s).replace(/'/g, "''") + "'";

const rows = SEED_PEOPLE.map((p, i) =>
  '  (' + [q(p.id), ...TEXT.map(f => q(p[f] || '')), i].join(', ') + ')'
).join(',\n');

const sets = TEXT.map(f => `  ${f} = v.${f}`).join(',\n');

const sql = `-- GENERATED by tools/gen-sync-sql.js — do not edit by hand.
-- FULL OVERWRITE of people text from assets/data.js. Only safe while the
-- family has not yet edited anything; use seed.sql after go-live instead.

update public.people p set
${sets},
  sort_order = v.sort_order::int
from (values
${rows}
) as v(id, ${TEXT.join(', ')}, sort_order)
where p.id = v.id;
`;

const out = path.join(__dirname, '..', 'supabase', 'sync-content.sql');
fs.writeFileSync(out, sql, 'utf8');
console.log(`Wrote ${out} (${SEED_PEOPLE.length} people, ${sql.length} chars)`);
